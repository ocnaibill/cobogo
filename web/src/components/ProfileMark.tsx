/** Marca de um perfil: ícone quando existe, letras caso contrário. `profile` é o nome legível. */
export function ProfileMark({ profile }: { profile?: string }) {
  let body: ReactNode;
  let kind = "other";
  switch (profile) {
    case "Bun":
      kind = "bun";
      body = (
        <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">
          <path d={BUN_PATH} />
        </svg>
      );
      break;
    case "Node.js":
      kind = "node";
      body = (
        <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">
          <path d={NODE_PATH} />
        </svg>
      );
      break;
    case "Site estático":
      kind = "static";
      body = "WWW";
      break;
    default:
      body = (profile ?? "?").slice(0, 2).toUpperCase();
  }
  return (
    <span className="profile-mark" data-profile={kind} aria-hidden="true">
      {body}
    </span>
  );
}
